def _add_table(doc, rows):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            t.cell(i, j).text = str(v)
    return t


def make_statement(path: str) -> None:
    """评估说明：含三法章节、表格勾稽错误、术语错写、数值与 Excel 不一致。"""
    doc = Document()
    doc.add_heading("评估说明", level=1)

    doc.add_heading("说明一 评估对象与评估范围", level=2)
    doc.add_paragraph(
        "本次评估对象为委托方持有的XX公司股东全部权益价值，评估范围为被评估单位于"
        "评估基准日期经审计的全部资产及负债。")
    doc.add_paragraph(
        "表 3-1 列入评估范围的资产汇总情况如下：")
    _add_table(doc, [
        ["科目", "账面价值", "评估价值"],
        ["流动资产", "1,000.00", "1,050.00"],
        ["非流动资产", "2,000.00", "2,200.00"],
        ["合计", "3,000.00", "3,500.00"],       # 应为 3,250.00 → doc_table_sum
    ])

    doc.add_heading("说明三 资产基础法评估说明", level=2)
    doc.add_paragraph(
        "本次对机器设备采用重置成本法进行评估，即按照重建或重置评估对象的思路，"
        "以重置成本扣除各项贬值确定评估价值。对部分设备采用重置成本法评估，"
        "避免了浪废材料与重复投入。")
    doc.add_paragraph(
        "固定资产账面价值 450.00 万元，评估价值 501.00 万元，增值率 11.33%。")

    doc.add_heading("说明四 收益法评估技术说明", level=2)
    doc.add_paragraph(
        "本次收益法采用现金流量折现法，预测期为 2023 年至 2025 年，"
        "折现率为 11.50%，永续期增长率取 0%。")          # Excel 为 12% → cross_doc_values
    doc.add_paragraph(
        "预测期营业收入由 2022 年的 900.00 万元增长至 2023 年的 2,000.00 万元，"
        "主要系新增产能释放所致。")
    doc.add_paragraph(
        "经测算，企业整体价值为 580.00 万元，股东全部权益价值为 260.00 万元。")

    doc.add_heading("说明五 评估结论及分析", level=2)
    doc.add_paragraph(
        "采用资产基础法评估的股东全部权益价值为 1,800.00 万元，"
        "采用收益法评估的股东全部权益价值为 260.00 万元，"
        "本次评估最终选取资产基础法结论作为评估结论。")
    doc.save(path)


def make_report(path: str) -> None:
    """评估报告全文：结论数值与底稿不一致、术语错写。"""
    doc = Document()
    doc.add_heading("资产评估报告", level=1)
    doc.add_paragraph("XX评报字（2023）第 0088 号")
    doc.add_paragraph(
        "委托人：XX集团有限公司。被评估单位：XX有限公司。"
        "评估目的：股权收购。评估基准日：2022年12月31日。")

    doc.add_heading("一、评估结论", level=2)
    doc.add_paragraph(
        "经实施上述评估程序，XX有限公司股东全部权益价值在评估基准日的"
        "评估结论为 265.00 万元。")                        # 底稿为 260 → conclusion_match

    doc.add_heading("二、评估方法", level=2)
    doc.add_paragraph(
        "本次评估采用资产基础法与收益法，未采用市场法。对机器设备采用重置成本法"
        "进行评估，未发现委托方提供的资料存在重大遗漏。")

    doc.add_heading("三、特别事项说明", level=2)
    doc.add_paragraph(
        "截至评估基准日，被评估单位部分房屋建筑物尚未办理产权证，"
        "详见评估说明。本次评估未考虑该权属瑕疵对评估结论的影响。")

    doc.add_heading("四、评估假设", level=2)
    doc.add_paragraph(
        "本次评估假设企业持续经营，假设宏观经济环境无重大变化，"
        "假设委托方提供的资料真实、完整、合法。")
    doc.save(path)


