import os
from docx import Document

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_tpl")


def save(name, lines):
    doc = Document()
    for ln in lines:
        doc.add_paragraph(ln)
    os.makedirs(OUT, exist_ok=True)
    doc.save(os.path.join(OUT, name))
    print("saved", name)


